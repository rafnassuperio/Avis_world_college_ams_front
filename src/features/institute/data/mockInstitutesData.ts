const BROKEN_404_PATTERN = "photo-1523050854058-8df90110c9f1";
const REPLACEMENT_IMAGE_URL = "https://images.unsplash.com/photo-1562774053-701939374585?auto=format&fit=crop&w=200&q=80";

export function getInstitutesList(): InstituteItem[] {
  const list = safeStorage.getItem<InstituteItem[]>(STORAGE_KEY_INSTITUTES, initialInstitutesData);
  let hasBroken = false;
  const healed = list.map((item) => {
    if (item.imageUrl && item.imageUrl.includes(BROKEN_404_PATTERN)) {
      hasBroken = true;
      return { ...item, imageUrl: REPLACEMENT_IMAGE_URL };
    }
    return item;
  });

  if (hasBroken) {
    safeStorage.setItem(STORAGE_KEY_INSTITUTES, healed);
  }

  return healed;
}

export function saveInstitutesList(list: InstituteItem[]): void {
  safeStorage.setItem(STORAGE_KEY_INSTITUTES, list);
}
